import { Icon } from "@metreeca/tile-cell/icon";
import { Link } from "@metreeca/tile-cell/link";
import { createElement } from "preact";
import "./ai.css";


/**
 * Creates an AI-generated content notice.
 *
 * Warns the reader that the resource on show was wholly or partially generated by AI tools, linking to the page that
 * explains how such content is produced; nothing is shown for a resource written by hand.
 */
export function AI({

	children

}: {

	/**
	 * Whether the resource was generated by AI tools; handwritten if omitted.
	 */
	children?: boolean

}) {

	return children ? createElement("ec2u-ai", {}, <>

		<Icon.Sparkles/>
		<span>AI-Generated Content</span>

		<Link look={"subtle"} href={"/about/ai"} title={"Learn More"}><Icon.Help/></Link>

	</>) : null;

}
