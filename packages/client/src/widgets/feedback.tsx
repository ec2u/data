import { Button } from "@metreeca/clay-widgets/button";
import { Icon } from "@metreeca/clay-widgets/icon";
import { Link } from "@metreeca/clay-widgets/link";
import { Strip } from "@metreeca/clay-widgets/strip";
import { Style } from "@metreeca/clay-widgets/style";
import { useTitle } from "@metreeca/clay/router";
import { feedback } from "../pages/about/feedback.js";


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

/**
 * Creates a feedback bar.
 *
 * Lets the reader report wrong or outdated content, or ask a question about it. The feedback action opens the feedback
 * page in a new tab, with the page on show already named. Where AI tools generated the content, even in part, the bar
 * turns to the fail colour, the action opens the feedback page set to report AI content, and a notice links to the
 * page explaining how such content is produced and why it may contain errors.
 *
 * The bar fills the width of the row holding it, with the feedback action at its start; where AI tools generated the
 * content, the feedback action moves to the end of the bar, next to the AI notice, so that the two read together.
 *
 * @param options The widget configuration
 *
 * @returns The feedback bar
 */
export function Feedback({

	ai = false

}: {

	/**
	 * Whether the content on show was generated by AI tools, even in part; no AI notice is shown if omitted.
	 */
	ai?: boolean

}) {

	const title = useTitle();

	function report(type?: string) {

		const query = new URLSearchParams({
			source: location.href,
			title,
			...(type ? { type } : {})
		});

		window.open(`${feedback.route}?${query}`, "_blank");

	}

	return <Style css={{

		color: ai ? "colorFailStroke" : undefined,
		fontWeight: ai ? "fontWeightStrong" : undefined

	}}>

		<Strip space={"spacing050"} align={"center"}>

			<Button
				look={"subtle"}
				mode={ai ? "danger" : "normal"} // matches the fail colour of the AI notice
				icon={<Icon.MessageSquare/>}
				title={"Provide feedback about this page"}
				onClick={() => report(ai ? "ai" : undefined)}
			/>

			{ai && <Link look={"subtle"} href={"/about/legal/ai"}>AI-Generated Content</Link>}

		</Strip>

	</Style>;

}
