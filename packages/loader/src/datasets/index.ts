import { Organization } from "@ec2u/data-loader/organizations/index.js";
import { EuroSciVocTopic } from "@ec2u/data-loader/taxonomies/pipes/euroscivoc.core.js";
import { University } from "@ec2u/data-loader/universities/index.js";
import { dct } from "@ec2u/data-loader/vocabularies/dct.js";
import { ec2u, Entity, rdfs } from "@ec2u/data-loader/vocabularies/ec2u.js";
import { boolean } from "@metreeca/blue/boolean";
import { reference } from "@metreeca/blue/reference";
import { multiple, optional, required, resource } from "@metreeca/blue/resource";
import { date, markdown, text } from "@metreeca/blue/string";


export function Dataset() {
	return resource(Resource, {

		space: dct,
		class: ec2u.Dataset

	}, {

		title: required(text),
		alternative: optional(text),
		description: required(markdown),

		created: optional(date),
		issued: optional(date),
		modified: optional(date),

		publisher: optional(reference(Organization)),

		source: optional(reference(Entity)),

		rights: optional(text),
		license: multiple(reference(Entity)),
		accessRights: optional(text),

		subject: multiple(reference(EuroSciVocTopic)),

		resources: multiple(reference(Resource), {

			foreign: true,

			reverse: ec2u.dataset

		})

	});
}

export function Resource() {
	return resource(Entity, {

		space: ec2u,
		class: ec2u.Resource

	}, {

		generated: optional(boolean, {

			description: "Flags resources wholly or partially generated by AI tools."

		}),

		dataset: required(reference(Dataset), {

			forward: ec2u,
			reverse: rdfs.member

		}),

		university: optional(reference(University))

	});
}
