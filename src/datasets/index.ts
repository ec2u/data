import { Organization } from "@/organizations/index.js";
import { Topic } from "@/taxonomies/index.js";
import { University } from "@/universities/index.js";
import { dct } from "@/vocabularies/dct.js";
import { ec2u, Entity, rdfs } from "@/vocabularies/ec2u.js";
import { boolean } from "@metreeca/blue/boolean";
import { reference } from "@metreeca/blue/reference";
import { property, resource, type ResourceShape } from "@metreeca/blue/resource";
import { date, markdown, text } from "@metreeca/blue/string";
import { multiple, optional, required } from "@metreeca/blue/value";


export function Dataset() {
	return resource({

		title: required(text),
		alternative: optional(text),
		description: required(markdown),

		created: optional(date),
		issued: optional(date),
		modified: optional(date),

		publisher: optional(reference(Organization)),

		source: optional(reference(Entity)),

		rights: optional(text),
		license: multiple(reference(Entity)),
		accessRights: optional(text),

		subject: multiple(reference(Topic)),

		resources: property({

			forward: ec2u.resource,
			reverse: ec2u.dataset

		}, multiple(reference(Resource, { foreign: true }))) // !!! foreign to property

	}, {

		namespace: dct,
		class: ec2u.Dataset,

		extends: Resource

	});
}

export function Resource() {
	return resource({

		generated: property({

			description: { en: "Flags resources wholly or partially generated by AI tools." }

		}, optional(boolean)),

		dataset: property({

			forward: ec2u,
			reverse: rdfs.member

		}, required(reference((): ResourceShape => Dataset()))),

		university: optional(reference((): ResourceShape => University()))

	}, {

		namespace: ec2u,
		class: ec2u.Resource,

		extends: Entity

	});
}
