/**
 * Gemini text translation.
 *
 * Provides a {@link Translator} rendering text in another language through the Gemini API, so that a job binding it
 * draws on the Gemini models without handling requests, credentials or rate quotas of its own.
 *
 * @module
 *
 * @see {@link https://ai.google.dev/gemini-api/docs Gemini API}
 */

import { createGoogleAI, text as output } from "@/_/muse-google/index.js";
import { type Translator } from "@/_/muse/translator/index.js";
import { file } from "@/_/host-node/files.js";
import { ThinkingLevel } from "@google/genai";
import { nameTag, type Tag } from "@metreeca/core/language";
import { markdown, type Text } from "@metreeca/core/strings";
import { service } from "@metreeca/gear";


/**
 * Creates a Gemini translator.
 *
 * Text is rendered by the {@link createGoogleAI Gemini client} bound to the enclosing execution, one request per
 * translation, so that credentials, endpoint and quota pacing are settled once by the consumer binding that client
 * rather than by the translator: a consumer translating at speed is held back by that pacing rather than rejected by
 * the API.
 *
 * Translations are generated at a fixed seed, so that the same text is rendered as consistently as the model allows,
 * and with thinking held to its minimum, so that a job translating in bulk is not charged for reasoning a rendering
 * task doesn't draw on.
 *
 * Blank text, and text already written in the target language, are handed to the API like any other, as
 * short-circuiting them is the business of the {@link translate} task.
 *
 * The client is resolved as the translator is created, so the enclosing execution must already be running by then. The
 * prompt steering the translation is read from the `.sys.md` file shipped alongside this module, so a deployment must
 * carry it next to the compiled code.
 *
 * @param options The translation options
 * @param options.model The Gemini model translations are generated by; if undefined, a general-purpose model is used
 *
 * @returns A translator rendering the text handed to it in the target language through the Gemini API
 *
 * @throws {@link !Error Error} If no execution is running, as the Gemini client is resolved from the enclosing one
 *
 * @throws {@link !Error Error} While translating, if the prompt shipped alongside the module cannot be read, whatever
 * the API reports on a request it cannot recover from, or if the model replies without output text
 *
 * @group Implementations
 */
export function createGoogleTranslator({

	model = "gemini-3.1-flash-lite"

}: {

	model?: string

} = {}): Translator {

	const ai = service(createGoogleAI);

	return async (text: Text, target: Tag, source?: Tag): Promise<Text> =>

		output(await ai.models.generateContent({

			model,

			contents: [
				markdown`
					- target: ${nameTag(target)}
					- source: ${source ? nameTag(source) : "unknown"}
				`,
				text
			],

			config: {

				seed: 0,

				thinkingConfig: {
					thinkingLevel: ThinkingLevel.MINIMAL
				},

				systemInstruction: await file(".sys.md", import.meta.url)

			}

		}));

}
